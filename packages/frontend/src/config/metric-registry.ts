// Helper to get metrics by category
export const getMetricsByCategory = (category: string): MetricConfig[] => {
    return Object.values(METRIC_REGISTRY).filter(m => m.category === category);
};

// Helper to get metrics by subcategory
export const getMetricsBySubcategory = (category: string, subcategory: string): MetricConfig[] => {
    return Object.values(METRIC_REGISTRY).filter(
        m => m.category === category && m.subcategory === subcategory
    );
};
