
export interface MetricConfig {
    id: string;
    name: string;
    shortName: string;
    description: string;
    category: string;
    subcategory?: string;

    // Data source
    apiEndpoint: string;
    tableName: string;
    valueField: string;

    // Display
    format: 'currency' | 'percent' | 'number' | 'decimal' | 'years' | 'days' | 'ratio' | 'index';
    precision: number;
    prefix?: string;
    suffix?: string;

    // Chart
    chartType: 'line' | 'area' | 'bar';
    colorScale: 'red-green' | 'green-red' | 'neutral'; // red-green = higher is better
    showAverage: boolean;
    showTrendline: boolean;

    // Geography availability
    geoLevels: ('national' | 'state' | 'metro' | 'county' | 'zip' | 'city')[];

    // Time series
    frequency: 'monthly' | 'quarterly' | 'annual';
    historyStart?: string; // e.g., '2000-01-01'
}

